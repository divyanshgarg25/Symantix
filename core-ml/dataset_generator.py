import json
import random
from typing import Iterator, List, Dict, Any

def generate_triplets(log_file_path: str) -> Iterator[Dict[str, str]]:
    """
    Parses a JSONL file of simulated logs and yields Triplet Data configurations.
    Uses generator pattern (yield) to prevent Out-Of-Memory (OOM) errors during ingestion.
    """
    # Group logs by trace_id and log_level
    traces: Dict[str, List[Dict[str, Any]]] = {}
    success_logs: List[Dict[str, Any]] = []

    with open(log_file_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            log = json.loads(line.strip())
            trace_id = log["trace_id"]
            
            if trace_id not in traces:
                traces[trace_id] = []
            traces[trace_id].append(log)
            
            if log["log_level"] == "INFO":
                success_logs.append(log)

    # Yield triplets
    for trace_id, logs in traces.items():
        errors = [l for l in logs if l["log_level"] in ["ERROR", "CRITICAL"]]
        if not errors:
            continue
            
        for anchor in errors:
            # Positive: another error in the same trace, or a different log in the same trace
            positives = [l for l in logs if l != anchor]
            if not positives:
                continue
            positive = random.choice(positives)
            
            # Negative: an INFO log from a completely different trace
            negatives = [l for l in success_logs if l["trace_id"] != trace_id]
            if not negatives:
                continue
            negative = random.choice(negatives)
            
            yield {
                "anchor": anchor["message"],
                "positive": positive["message"],
                "negative": negative["message"]
            }

